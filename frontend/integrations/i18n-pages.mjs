/**
 *  Plugin to automatically ensure page translation files are imported, available and strongly typed.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const START = "// <generated:pages>";
const END = "// </generated:pages>";

const I18N_DIR = "src/i18n";
const PAGE_TRANSLATION_FILE = "page-translations.ts";

/**
 * Finds all subfolders of the i18n directory containing translation files and returns their path relative
 * to the i18n directory (e.g. "prosjekter" or "account/create").
 */
function findPageFolders(root, dir = root) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (!entry.isDirectory()) return [];

    const folder = path.join(dir, entry.name);
    const hasTranslations = fs.readdirSync(folder).some(file => file.endsWith(".json"));
    const own = hasTranslations ? [path.relative(root, folder).split(path.sep).join("/")] : [];

    return [...own, ...findPageFolders(root, folder)];
  });
}

function generate(i18nDir, locales) {
  const identifiers = new Set();
  const imports = [];
  const entries = [];

  for (const page of findPageFolders(i18nDir).sort()) {
    const camel = page.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));
    const base = /^\d/.test(camel) ? `_${camel}` : camel;
    const names = locales.map(locale => {
      const file = path.join(i18nDir, page, `${locale}.json`);
      if (!fs.existsSync(file)) {
        throw new Error(
          `[i18n-pages] Missing translation file: ${I18N_DIR}/${page}/${locale}.json`
        );
      }

      const name = `${base}${locale[0].toUpperCase()}${locale.slice(1)}`;
      if (identifiers.has(name)) {
        throw new Error(`[i18n-pages] Ambiguous import name '${name}' for page '${page}'`);
      }
      identifiers.add(name);
      imports.push(`import ${name} from "./${page}/${locale}.json";`);
      return [locale, name];
    });

    const values = names.map(([locale, name]) => `${locale}: ${name}`).join(", ");
    entries.push(`  "${page}": { ${values} },`);
  }

  return [
    START,
    "// IMPORTANT NOTICE:",
    "// File is generated by integrations/i18n-pages.mjs from the subfolders of /i18n. Do not edit manually!",
    ...imports,
    "",
    "export const pageUi = {",
    ...entries,
    "} as const;",
    "",
    "export type PageKey = keyof typeof pageUi;",
    END,
  ].join("\n");
}

function sync(i18nDir, locales, logger) {
  const uiFile = path.join(i18nDir, PAGE_TRANSLATION_FILE);
  const source = fs.readFileSync(uiFile, "utf8");
  const block = generate(i18nDir, locales);

  const start = source.indexOf(START);
  const end = source.indexOf(END);
  const next =
    start === -1 || end === -1
      ? `${source.trimEnd()}\n\n${block}\n`
      : source.slice(0, start) + block + source.slice(end + END.length);

  if (next !== source) {
    fs.writeFileSync(uiFile, next);
    logger.info(`Updated page translations in src/${I18N_DIR}/${PAGE_TRANSLATION_FILE}`);
  }
}

/**
 * Keeps the page translation registry in src/i18n/ui.ts in sync with the subfolders of src/i18n.
 */
export default function i18nPages() {
  let i18nDir;
  let locales;

  return {
    name: "i18n-pages",
    hooks: {
      "astro:config:setup": ({ config, logger }) => {
        i18nDir = path.join(fileURLToPath(config.root), I18N_DIR);
        locales = config.i18n.locales.map(locale =>
          typeof locale === "string" ? locale : locale.path
        );
        sync(i18nDir, locales, logger);
      },
      "astro:server:setup": ({ server, logger }) => {
        const update = file => {
          const relative = path.relative(i18nDir, file);
          if (!relative.startsWith("..") && relative.includes(path.sep)) {
            try {
              sync(i18nDir, locales, logger);
            } catch (error) {
              logger.error(error.message);
            }
          }
        };

        server.watcher.add(i18nDir);
        for (const event of ["add", "unlink", "addDir", "unlinkDir"]) {
          server.watcher.on(event, update);
        }
      },
    },
  };
}
